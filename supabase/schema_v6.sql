-- ----------------------------------------------------------------------------
-- 1. class-photos 버킷을 완전 공개로 전환
-- 교시별 메모 사진, 공지사항 첨부 이미지는 애초에 학급 전체가 보는 공개 콘텐츠라
-- 민감하지 않다. 버킷을 public 으로 바꾸면 서명 URL 없이도(로그인 여부 상관없이)
-- 바로 이미지 URL로 접근 가능해진다. (개인 공부 인증 사진이 있는 study-photos
-- 버킷은 그대로 비공개 유지 — 이건 본인/관리자만 봐야 한다.)
-- ----------------------------------------------------------------------------
update storage.buckets set public = true where id = 'class-photos';

drop policy if exists class_photos_select on storage.objects;
create policy class_photos_select on storage.objects for select
  using (bucket_id = 'class-photos');

-- ----------------------------------------------------------------------------
-- 2. 랭킹 계산 함수를 비로그인 사용자도 호출할 수 있도록 권한 확장
-- ----------------------------------------------------------------------------
grant execute on function public.weekly_rankings(date, date) to anon;

-- ----------------------------------------------------------------------------
-- 3. 익명 물품 신청 공개 통계 함수도 비로그인 사용자가 볼 수 있도록 권한 확장
-- ----------------------------------------------------------------------------
grant execute on function public.item_requests_public() to anon;

